    /**
     * get EXCLUSIVE rowlock(SELECT FOR UPDATE semantics).
     *
     * <p>sameone txnId multiple times to same key callisreentrantsecurity({@link ReentrantLock}).
     *
     * <p><b>H-7 lock order convention (prevent deadlock)</b>: caller must acquire locks by key
     * lexicographic ascending. in ScanQueryIR/UpdateQueryIR pathaboveby Backend forcewill keys
     * sort. commitLock({@link #getCommitLock()})getorderconstraint:
     *
     * <ul>
     *   <li>any moment notallowinhold rowLock whileget commitLock;
     *   <li>commitLock onlyin ValidateStage + PublishStage withinhold, duringnotgetnew rowLock;
     * </ul>
     *
     * becausethis rowLock and commitLock will never form a cyclewait.
     *
     * @param key row key(preventdefenseity clone)
     * @param txnId transaction ID
     * @param timeoutMs waittimeout (milliseconds), &lt;=0 tableshowimmediatelyreturn
     * @throws LockTimeoutException lockwaittimeout
     * @throws InterruptedException waitduringthreadbeinterrupt
     */
    public void acquireForUpdate(byte[] key, long txnId, long timeoutMs)
            throws InterruptedException {
        if (key == null) {
            throw new IllegalArgumentException("key must not be null");
        }
        ByteBuffer keyBuf = ByteBuffer.wrap(key.clone());
        ReentrantLock l = rowLocks.get(keyBuf, k -> new ReentrantLock());
        boolean acquired = l.tryLock(Math.max(0, timeoutMs), TimeUnit.MILLISECONDS);
        if (!acquired) {
            throw new LockTimeoutException(
                    "FOR UPDATE timeout: txn="
                            + txnId
                            + " keyHash="
                            + java.util.Arrays.hashCode(key)
                            + " timeoutMs="
                            + timeoutMs);
        }
        // reentrantcountcount > 1 tableshowsameonetransactionwithinrepeated acquire sameone key --
        // alreadyrecordthroughi.e.can
        if (l.getHoldCount() == 1) {
            txnHeldKeys.computeIfAbsent(txnId, t -> new CopyOnWriteArrayList<>()).add(keyBuf);
        }
        log.debug(
                "Shard {}: txn {} acquired FOR UPDATE on key (holdCount={})",
                shardId,
                txnId,
                l.getHoldCount());
    }

    /**
     * releasetransactionholdallrowlock.in commit/abort/cleanupTxn endcall(finally blockfallback).
     *
     * <p>H-6 memorymanage: lockreleaseafterifnowaitone, mainactionfrom cache removebyreleasememory.
     *
     * @param txnId transaction ID
     */
    public void releaseAll(long txnId) {
        List<ByteBuffer> keys = txnHeldKeys.remove(txnId);
        if (keys == null || keys.isEmpty()) {
            return;
        }
        for (ByteBuffer keyBuf : keys) {
            ReentrantLock l = rowLocks.getIfPresent(keyBuf);
            if (l == null) continue;
            // releasethetransactionholdallreentranttimecount
            try {
                while (l.isHeldByCurrentThread()) {
                    l.unlock();
                }
            } catch (IllegalMonitorStateException ignored) {
                // nothold → ignore(may have been by otherpathrelease)
            }
            // locknootherwaitand not by anythreadhold → from cache remove
            if (!l.hasQueuedThreads() && !l.isLocked()) {
                rowLocks.invalidate(keyBuf);
            }
        }
        log.debug("Shard {}: released {} row locks for txn {}", shardId, keys.size(), txnId);
    }

    /**
     * checktransactionwhetherholdspecified key rowlock(provide ValidateStage H-8 fixuse).
     *
     * @param key row key
     * @param txnId transaction ID
     * @return true if the txn holds an EXCLUSIVE lock on this key
     */
    public boolean holdsExclusiveLock(byte[] key, long txnId) {
        if (key == null) return false;
        List<ByteBuffer> keys = txnHeldKeys.get(txnId);
        if (keys == null || keys.isEmpty()) return false;
        ByteBuffer probe = ByteBuffer.wrap(key);
        for (ByteBuffer held : keys) {
            if (held.equals(probe)) return true;
        }
        return false;
    }

