    /**
     * atomicverify+update(carryWALsupport). fixP1-C3: inlockprotectunder,
     * firstwriteWALagainupdateversion, ensurecrash recoverywhendatanotlose.
     *
     * <p>executeorder(incommitLockprotectunder):
     *
     * <ol>
     *   <li>OCCverify(noconflictonly thencontinue)
     *   <li>WAL SYNC_MARKERwrite(durability)
     *   <li>versionupdate(visibleity)
     * </ol>
     *
     * <p>note: WALwritefailwillthrowRuntimeExceptionblockcommitbyensuredurability.
     *
     * @param txnCtx transaction context
     * @param commitLock coordinatorlevelcommitlock
     * @param wal WALinstance(may benull, tableshownotrequiresWALdurability)
     * @return verifyresult, includesuccess/failstateandcommitTsorconflictdetails
     */
    public AtomicValidateResult validateAndUpdateAtomic(
            TxnContext txnCtx, ReentrantLock commitLock, io.github.rawwise.backend.wal.WAL wal) {
        if (txnCtx == null) {
            throw new IllegalArgumentException("Transaction context must not be null");
        }
        if (!txnCtx.isActive()
                && txnCtx.currentState() != TxnState.PREPARING
                && txnCtx.currentState() != TxnState.DATA_DURABLE) {
            throw new IllegalArgumentException(
                    "Transaction "
                            + txnCtx.txnId()
                            + " is not active or preparing: "
                            + txnCtx.currentState());
        }

        commitLock.lock();
        try {
            // step1: executeOCCverify(collectallconflict)
            List<ConflictReport.ConflictEntry> allConflicts = new ArrayList<>();

            // 1a. checkwrite-writeconflict
            Map<ByteBuffer, OperationSet.OpEntry> writeEntries =
                    txnCtx.operationSet().writeEntries();
            for (Map.Entry<ByteBuffer, OperationSet.OpEntry> entry : writeEntries.entrySet()) {
                byte[] key = entry.getKey().array();
                OperationSet.OpEntry opEntry = entry.getValue();

                VersionInfo info = versionCache.getIfPresent(entry.getKey());
                if (info == null) {
                    info = skipListMap.get(entry.getKey());
                }
                long currentCommitTs = info != null ? info.commitTs() : 0;

                log.debug(
                        "OCC write-write check: key={} currentCommitTs={} baseVersion={} startTs={} txnId={}",
                        new String(key),
                        currentCommitTs,
                        opEntry.baseVersion(),
                        txnCtx.startTs(),
                        txnCtx.txnId());

                if (currentCommitTs > opEntry.baseVersion() && currentCommitTs > txnCtx.startTs()) {
                    return AtomicValidateResult.conflict(
                            key, opEntry.baseVersion(), currentCommitTs);
                }
            }

            // 1b. checkread-writeconflict(REPEATABLE_READand above level)
            if (txnCtx.isolationLevel() == IsolationLevel.REPEATABLE_READ
                    || txnCtx.isolationLevel() == IsolationLevel.SERIALIZABLE) {
                Map<ByteBuffer, OperationSet.OpEntry> readEntries =
                        txnCtx.operationSet().readEntries();
                for (Map.Entry<ByteBuffer, OperationSet.OpEntry> entry : readEntries.entrySet()) {
                    byte[] key = entry.getKey().array();
                    OperationSet.OpEntry opEntry = entry.getValue();

                    VersionInfo info = versionCache.getIfPresent(entry.getKey());
                    if (info == null) {
                        info = skipListMap.get(entry.getKey());
                    }
                    long currentCommitTs = info != null ? info.commitTs() : 0;

                    if (currentCommitTs > opEntry.readCommitTs()) {
                        return AtomicValidateResult.conflict(
                                key, opEntry.readCommitTs(), currentCommitTs);
                    }
                }
            }

            // 1c. phantom readdetection(SERIALIZABLElevel)- rangeaware
            if (txnCtx.isolationLevel() == IsolationLevel.SERIALIZABLE
                    && !txnCtx.operationSet().isReadEmpty()) {
                List<ConflictReport.ConflictEntry> conflicts = new ArrayList<>();
                detectPhantomConflicts(txnCtx, conflicts);
                if (!conflicts.isEmpty()) {
                    ConflictReport.ConflictEntry first = conflicts.get(0);
                    return AtomicValidateResult.conflict(
                            first.conflictKey(), -1, first.conflictingVersion());
                }
            }

            // step2: noconflict, firstwriteWALagainupdateversion(durabilitypriorityinvisibleity)
            if (wal != null) {
                try {
                    wal.insertSyncMarker(txnCtx.tableId());
                    log.debug(
                            "Shard {}: WAL SYNC_MARKER written for txn {}",
                            shardId,
                            txnCtx.txnId());
                } catch (Exception e) {
                    throw new RuntimeException(
                            "Shard "
                                    + shardId
                                    + ": WAL SYNC_MARKER write failed for txn "
                                    + txnCtx.txnId()
                                    + ", aborting commit to ensure durability",
                            e);
                }
            }

            // step3: atomicupdateallwriteoperationkeyversion
            Set<ByteBuffer> writeKeys = txnCtx.operationSet().writeKeys();
            long newCommitTs = -1;
            if (!writeKeys.isEmpty()) {
                newCommitTs = nextCommitTs();
                VersionInfo versionInfo = new VersionInfo(newCommitTs, txnCtx.txnId());
                for (ByteBuffer keyBuffer : writeKeys) {
                    versionCache.put(keyBuffer, versionInfo);
                    skipListMap.put(keyBuffer, versionInfo);
                }
                log.debug(
                        "Shard {}: atomically updated {} keys to commitTs={}, txnId={}",
                        shardId,
                        writeKeys.size(),
                        newCommitTs,
                        txnCtx.txnId());
            }

            return AtomicValidateResult.ok(newCommitTs);

        } finally {
            commitLock.unlock();
        }
    }
