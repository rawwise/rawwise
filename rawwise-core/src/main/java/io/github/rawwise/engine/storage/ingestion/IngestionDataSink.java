package io.github.rawwise.engine.storage.ingestion;

import java.util.List;

public interface IngestionDataSink extends AutoCloseable {

    FlushResult flushBatch(
            String tableId,
            long txnId,
            List<byte[]> keys,
            List<byte[]> values,
            long schemaVersion,
            long minSeq,
            long maxSeq)
            throws SinkRetryableException, SinkFatalException;

    default FlushResult flushBatch(
            String tableId,
            long txnId,
            List<byte[]> keys,
            List<byte[]> values,
            long schemaVersion,
            long minSeq,
            long maxSeq,
            long checkpointId,
            int subTaskIndex,
            long writerInstanceId)
            throws SinkRetryableException, SinkFatalException {
        return flushBatch(tableId, txnId, keys, values, schemaVersion, minSeq, maxSeq);
    }

    void prepare(String tableId, List<String> pendingIds, long txnId)
            throws SinkRetryableException, SinkFatalException;

    void commit(String tableId, List<String> pendingIds, long txnId, long commitTs)
            throws SinkRetryableException, SinkFatalException;

    void rollback(String tableId, List<String> pendingIds, long txnId) throws SinkFatalException;

    default void releasePrepared(String tableId, List<String> pendingIds, long txnId) {}

    RecoveryResult recoverPending(String tableId) throws SinkRetryableException, SinkFatalException;

    String sinkType();

    @Override
    void close();

    record FlushResult(List<String> pendingIds) {
        /** Returns the pending IDs generated by THIS flush operation. */
        public List<String> pendingIds() {
            return pendingIds;
        }

        public FlushResult {
            pendingIds = List.copyOf(pendingIds);
        }
    }

    record RecoveryResult(int recoveredCount, int cleanedCount, List<String> errors) {
        public RecoveryResult {
            errors = List.copyOf(errors);
        }
    }
}
